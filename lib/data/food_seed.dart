// Generic foods: typical values per 100 g/ml from common nutrition tables
// (rounded). Chain items are APPROXIMATE (source 'chain', shown with "~"):
// they come from published menu figures as remembered, not from a live scrape.

Food _g(String name, double kcal, double p, double c, double f, [double serving = 100, String label = '']) =>
    Food(name: name, kcal100: kcal, p100: p, c100: c, f100: f, servingG: serving, servingLabel: label, source: 'own');

/// Per-item figures -> per-100g so one code path handles everything.
Food _chain(String brand, String name, double grams, double kcal, double p, double c, double f) {
  final k = 100 / grams;
  return Food(
      name: name,
      brand: brand,
      kcal100: kcal * k,
      p100: p * k,
      c100: c * k,
      f100: f * k,
      servingG: grams,
      servingLabel: '1 szt.',
      source: 'chain');
}

